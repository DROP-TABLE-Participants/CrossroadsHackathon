using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace ErpGenerator.Runtime.GeneratedPrimitives.Generator;

[Generator(LanguageNames.CSharp)]
public sealed class RuntimeGeneratedPrimitiveCatalogGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var declarations = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is RecordDeclarationSyntax or EnumDeclarationSyntax,
                static (syntaxContext, _) => Describe(syntaxContext))
            .Where(static declaration => declaration is not null)
            .Select(static (declaration, _) => declaration!)
            .Collect();

        context.RegisterSourceOutput(declarations, static (productionContext, values) =>
        {
            var source = Emit(values);
            productionContext.AddSource(
                "RuntimeGeneratedPrimitiveGeneratedCatalog.g.cs",
                SourceText.From(source, Encoding.UTF8));
        });
    }

    private static PrimitiveDeclaration? Describe(GeneratorSyntaxContext context)
    {
        var path = context.Node.SyntaxTree.FilePath.Replace('\\', '/');
        if (!path.Contains("/ErpGenerator.Runtime.GeneratedPrimitives/Generated/", StringComparison.Ordinal))
        {
            return null;
        }

        return context.Node switch
        {
            RecordDeclarationSyntax record when context.SemanticModel.GetDeclaredSymbol(record) is INamedTypeSymbol symbol =>
                new PrimitiveDeclaration(
                    Key(symbol),
                    "record",
                    record.ParameterList?.Parameters.Select(parameter => DescribeParameter(context.SemanticModel, parameter))
                        .Where(member => member is not null)
                        .Select(member => member!)
                        .ToImmutableArray() ?? ImmutableArray<PrimitiveMember>.Empty,
                    record.ParameterList is not null &&
                    (record.ParameterList.Parameters.Count == 0 ||
                     record.ParameterList.Parameters.All(parameter => DescribeParameter(context.SemanticModel, parameter) is not null))),
            EnumDeclarationSyntax @enum when context.SemanticModel.GetDeclaredSymbol(@enum) is INamedTypeSymbol symbol =>
                new PrimitiveDeclaration(
                    Key(symbol),
                    "enum",
                    @enum.Members.Select(member => DescribeEnumMember(context.SemanticModel, member))
                        .Where(value => value is not null)
                        .Select(value => value!)
                        .ToImmutableArray(),
                    @enum.Members.Count > 0 &&
                    @enum.Members.All(member => DescribeEnumMember(context.SemanticModel, member) is not null)),
            _ => null
        };
    }

    private static PrimitiveMember? DescribeParameter(SemanticModel semanticModel, ParameterSyntax parameter)
    {
        var type = parameter.Type is null ? null : semanticModel.GetTypeInfo(parameter.Type).Type;
        if (type is null || type.TypeKind == TypeKind.Error)
        {
            return null;
        }

        return new PrimitiveMember(
            parameter.Identifier.ValueText,
            type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
            parameter.Default is null && type.NullableAnnotation != NullableAnnotation.Annotated,
            null);
    }

    private static PrimitiveMember? DescribeEnumMember(
        SemanticModel semanticModel,
        EnumMemberDeclarationSyntax member)
    {
        if (semanticModel.GetDeclaredSymbol(member) is not IFieldSymbol { ConstantValue: not null } symbol)
        {
            return null;
        }

        return new PrimitiveMember(
            member.Identifier.ValueText,
            "enum_member",
            true,
            Convert.ToString(symbol.ConstantValue, System.Globalization.CultureInfo.InvariantCulture));
    }

    private static string Key(INamedTypeSymbol symbol) =>
        symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
            .Replace("global::", string.Empty);

    private static string Emit(ImmutableArray<PrimitiveDeclaration> declarations)
    {
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("namespace ErpGenerator.Runtime.GeneratedPrimitives;");
        source.AppendLine("internal static class RuntimeGeneratedPrimitiveGeneratedCatalog");
        source.AppendLine("{");
        source.AppendLine("    internal static readonly global::System.Collections.Generic.IReadOnlyList<RuntimeGeneratedPrimitiveDefinition> Definitions =");
        source.AppendLine("        global::System.Array.AsReadOnly(new RuntimeGeneratedPrimitiveDefinition[]");
        source.AppendLine("        {");
        foreach (var declaration in declarations
                     .Where(value => value.Complete)
                     .OrderBy(value => value.Key, StringComparer.Ordinal))
        {
            source.Append("            new RuntimeGeneratedPrimitiveDefinition(")
                .Append(Literal(declaration.Key)).Append(", ")
                .Append(Literal(declaration.Kind)).AppendLine(",");
            source.AppendLine("                global::System.Array.AsReadOnly(new RuntimeGeneratedPrimitiveMemberDefinition[]");
            source.AppendLine("                {");
            foreach (var member in declaration.Members)
            {
                source.Append("                    new RuntimeGeneratedPrimitiveMemberDefinition(")
                    .Append(Literal(member.Name)).Append(", ")
                    .Append(Literal(member.TypeName)).Append(", ")
                    .Append(member.Required ? "true" : "false").Append(", ")
                    .Append(member.ConstantValue is null ? "null" : Literal(member.ConstantValue))
                    .AppendLine("),");
            }
            source.AppendLine("                })),");
        }
        source.AppendLine("        });");
        source.AppendLine("}");
        return source.ToString();
    }

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);

    private sealed record PrimitiveDeclaration(
        string Key,
        string Kind,
        ImmutableArray<PrimitiveMember> Members,
        bool Complete);

    private sealed record PrimitiveMember(
        string Name,
        string TypeName,
        bool Required,
        string? ConstantValue);
}
